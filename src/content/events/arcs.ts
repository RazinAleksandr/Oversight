/** An election (not a party congress) happens within the next `within` turns. */
const electionSoon = (s: GameState, within: number): boolean =>
  (s.government?.calendar ?? []).some((e) => e.kind === 'election' && e.turn > s.turn && e.turn <= s.turn + within);

const clamp = (x: number, lo: number, hi: number) => Math.max(lo, Math.min(hi, x));

